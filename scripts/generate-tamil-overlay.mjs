#!/usr/bin/env node
/**
 * Collects every authored English string that has no Tamil overlay yet and
 * asks Sarvam-Translate for a glossary-pinned Tamil version, appending the
 * results to lib/i18n/ta-overlay.data.ts with `reviewed: false`.
 *
 *   SARVAM_API_KEY=... node scripts/generate-tamil-overlay.mjs [--limit 50] [--dry-run]
 *
 * Without a key the script reports how many strings are missing and exits 0.
 * Reviewed entries are never overwritten. See docs/SARVAM.md.
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { protectedGlossaryForms } from "../lib/concept-bridge.ts";
import { DEMO_JOURNEY_COPY } from "../lib/demo-journey-copy.ts";
import { EVAPORATION_CONCEPT_STAGES } from "../lib/evaporation-concept.ts";
import { FRACTION_CONCEPT_STAGES } from "../lib/fraction-concept.ts";
import { GROWTH_NODES } from "../lib/growth-graph-catalog.ts";
import { TAMIL_OVERLAY_ENTRIES } from "../lib/i18n/ta-overlay.data.ts";
import { SEED_LESSONS } from "../lib/seeded-journey.ts";
import { SEEDED_DOUBTS } from "../lib/seeded-doubts.ts";
import { mathsTokensIn, pinProtectedForms, restoreProtectedForms } from "../lib/translation-pinning.ts";
import { PLACES } from "../lib/world/places.ts";
import { STATIONS } from "../lib/world/stations.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, "lib/i18n/ta-overlay.data.ts");
const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const limitIndex = args.indexOf("--limit");
const limit = limitIndex >= 0 ? Number(args[limitIndex + 1]) : 40;

/** Walks authored copy objects and yields every `{ hi, en }` English string. */
function* englishStrings(value, seen = new Set()) {
  if (!value || typeof value !== "object") return;
  if (typeof value.en === "string" && typeof value.hi === "string") {
    if (!seen.has(value.en)) {
      seen.add(value.en);
      yield value.en;
    }
    return;
  }
  for (const child of Array.isArray(value) ? value : Object.values(value)) yield* englishStrings(child, seen);
}

const sources = [FRACTION_CONCEPT_STAGES, EVAPORATION_CONCEPT_STAGES, DEMO_JOURNEY_COPY, SEED_LESSONS, SEEDED_DOUBTS, GROWTH_NODES, PLACES, STATIONS];
const seen = new Set();
const missing = [];
for (const source of sources) {
  for (const english of englishStrings(source, seen)) {
    if (!(english in TAMIL_OVERLAY_ENTRIES) && english.length <= 400) missing.push(english);
  }
}

console.log(`Tamil overlay: ${Object.keys(TAMIL_OVERLAY_ENTRIES).length} entries present, ${missing.length} authored strings missing.`);

const key = process.env.SARVAM_API_KEY?.trim();
if (!key || dryRun) {
  if (!key) console.log("SARVAM_API_KEY is not set; nothing was translated.");
  process.exit(0);
}

const protectedForms = protectedGlossaryForms();
const additions = {};
for (const english of missing.slice(0, limit)) {
  const { text, pinned } = pinProtectedForms(english, [...protectedForms, ...mathsTokensIn(english)]);
  const response = await fetch("https://api.sarvam.ai/translate", {
    method: "POST",
    headers: { "api-subscription-key": key, "content-type": "application/json" },
    body: JSON.stringify({
      input: text,
      source_language_code: "en-IN",
      target_language_code: "ta-IN",
      model: "sarvam-translate:v1",
      mode: "classic-colloquial",
      numerals_format: "international",
    }),
  });
  if (!response.ok) {
    console.error(`Sarvam returned ${response.status} for: ${english.slice(0, 60)}…`);
    continue;
  }
  const payload = await response.json();
  const restored = typeof payload.translated_text === "string" ? restoreProtectedForms(payload.translated_text, pinned) : null;
  if (!restored || !/[\u0B80-\u0BFF]/.test(restored)) {
    console.error(`Rejected (pin or script check) for: ${english.slice(0, 60)}…`);
    continue;
  }
  additions[english] = restored;
}

const count = Object.keys(additions).length;
if (count === 0) {
  console.log("No new entries.");
  process.exit(0);
}

const escape = (value) => JSON.stringify(value);
const block = Object.entries(additions)
  .map(([english, ta]) => `  ${escape(english)}: { ta: ${escape(ta)}, reviewed: false },`)
  .join("\n");
const source = fs.readFileSync(target, "utf8");
const marker = "\n};\n";
if (!source.endsWith(marker)) throw new Error("ta-overlay.data.ts must end with the entries object");
fs.writeFileSync(target, `${source.slice(0, -marker.length)}\n\n  // Generated by scripts/generate-tamil-overlay.mjs (Sarvam-Translate, glossary pinned) — awaiting review\n${block}${marker}`);
console.log(`Appended ${count} unreviewed Tamil entries to lib/i18n/ta-overlay.data.ts.`);
